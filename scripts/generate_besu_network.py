"""Generate a fresh 3-validator QBFT network for LexCorp2 (chain id 13371).

  python scripts/generate_besu_network.py            # refuses if chain data exists
  python scripts/generate_besu_network.py --force    # only after archiving network/besu/data

* New validator node keys are generated locally by Besu itself and written to
  network/besu/networkFiles/keys/ (git-ignored). They are never printed.
* The genesis pre-funds NO account: the network is zero-fee (zeroBaseFee + min gas
  price 0), so no well-known or shared funded key exists, and wallets need no funding.
  Authorization is enforced by the AssetNFT contract roles, not by gas.
* The generated compose file publishes JSON-RPC on 127.0.0.1 only, enables only the
  ETH/NET/WEB3/QBFT APIs, and allows no browser origins (browsers go through the
  authenticated backend relay /api/chain/rpc).
"""

import argparse
import json
import shutil
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
BESU = ROOT / "network" / "besu"
IMAGE = "hyperledger/besu:26.8.1"

CONFIG = {
    "genesis": {
        "config": {
            "chainId": 13371,
            "homesteadBlock": 0, "eip150Block": 0, "eip155Block": 0, "eip158Block": 0,
            "byzantiumBlock": 0, "constantinopleBlock": 0, "petersburgBlock": 0, "istanbulBlock": 0,
            "berlinBlock": 0, "londonBlock": 0, "shanghaiBlock": 0,
            "zeroBaseFee": True,
            "qbft": {"blockperiodseconds": 2, "epochlength": 30000, "requesttimeoutseconds": 4},
        },
        "gasLimit": "0x1fffffffffffff",
        "difficulty": "0x1",
        "coinbase": "0x0000000000000000000000000000000000000000",
        "alloc": {},
    },
    "blockchain": {"nodes": {"generate": True, "count": 3}},
}

COMPOSE = """# GENERATED by scripts/generate_besu_network.py - LexCorp2 QBFT network (chain 13371)
x-besu-def: &besu-def
  image: {image}
  restart: unless-stopped
  entrypoint:
    - besu
    - --data-path=/opt/besu/data
    - --genesis-file=/opt/besu/networkFiles/genesis.json
    - --rpc-http-enabled
    - --rpc-http-api=ETH,NET,WEB3,QBFT
    - --rpc-http-host=0.0.0.0
    - --host-allowlist=localhost,127.0.0.1
    - --min-gas-price=0
    - --sync-mode=FULL
    - --rpc-http-max-active-connections=80

services:
  node1:
    <<: *besu-def
    container_name: besu_node1
    command: >
      --node-private-key-file=/opt/besu/networkFiles/keys/node1/key
      --p2p-port=30303
      --rpc-http-port=8545
    volumes:
      - ./networkFiles:/opt/besu/networkFiles:ro
      - ./data/node1:/opt/besu/data
    ports:
      - "127.0.0.1:8545:8545"
    networks:
      besu-network:
        ipv4_address: 172.18.0.10
{followers}
networks:
  besu-network:
    driver: bridge
    ipam:
      config:
        - subnet: 172.18.0.0/24
"""

FOLLOWER = """
  node{n}:
    <<: *besu-def
    container_name: besu_node{n}
    command: >
      --node-private-key-file=/opt/besu/networkFiles/keys/node{n}/key
      --p2p-port=30303
      --bootnodes=enode://{enode}@172.18.0.10:30303
    volumes:
      - ./networkFiles:/opt/besu/networkFiles:ro
      - ./data/node{n}:/opt/besu/data
    networks:
      besu-network:
        ipv4_address: 172.18.0.1{ip}
"""


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--force", action="store_true")
    a = ap.parse_args()
    data = BESU / "data"
    if data.exists() and any(data.rglob("*")) and not a.force:
        print("network/besu/data is not empty. Archive it first, then re-run with --force.")
        return 2

    work = BESU / "_generate"
    shutil.rmtree(work, ignore_errors=True)
    work.mkdir()
    (work / "config.json").write_text(json.dumps(CONFIG, indent=2), encoding="utf-8")
    subprocess.run(
        ["docker", "run", "--rm", "-v", f"{work.as_posix()}:/work", IMAGE, "operator", "generate-blockchain-config",
         "--config-file=/work/config.json", "--to=/work/out", "--private-key-file-name=key"],
        check=True, stdout=subprocess.DEVNULL,
    )
    out = work / "out"
    keys = sorted(p for p in (out / "keys").iterdir() if p.is_dir())
    if len(keys) != 3:
        raise SystemExit("expected 3 generated validator keys")

    nf = BESU / "networkFiles"
    shutil.rmtree(nf / "keys", ignore_errors=True)
    (nf / "keys").mkdir(parents=True)
    validators = []
    for i, k in enumerate(keys, start=1):
        dst = nf / "keys" / f"node{i}"
        dst.mkdir()
        shutil.copy2(k / "key", dst / "key")
        shutil.copy2(k / "key.pub", dst / "key.pub")
        validators.append(k.name)
    genesis = json.loads((out / "genesis.json").read_text(encoding="utf-8"))
    genesis["alloc"] = {}
    (nf / "genesis.json").write_text(json.dumps(genesis, indent=2), encoding="utf-8")

    enode = (nf / "keys" / "node1" / "key.pub").read_text(encoding="utf-8").strip().removeprefix("0x")
    followers = "".join(FOLLOWER.format(n=n, enode=enode, ip=n - 1) for n in (2, 3))
    (BESU / "docker-compose-active.yml").write_text(COMPOSE.format(image=IMAGE, followers=followers), encoding="utf-8")
    shutil.rmtree(work, ignore_errors=True)
    for n in (1, 2, 3):
        (data / f"node{n}").mkdir(parents=True, exist_ok=True)
    print("Generated QBFT network: chain 13371, validators:", ", ".join(validators))
    print("Genesis alloc: none (zero-fee network). Keys: network/besu/networkFiles/keys/ (git-ignored)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
