"""Generate a fresh 3-validator QBFT network for LexCorp (chain id 13371).

  python scripts/generate_besu_network.py            # refuses if chain data exists
  python scripts/generate_besu_network.py --force    # moves existing chain data to
                                                     # network/besu/data_archived_<time>/ first

* New validator node keys are generated locally by Besu itself and written to
  network/besu/networkFiles/keys/ (git-ignored). They are never printed.
* The genesis pre-funds NO account: the network is zero-fee (zeroBaseFee + min gas
  price 0), so no well-known or shared funded key exists, and wallets need no funding.
  Authorization is enforced by the AssetNFT contract roles, not by gas.
* network/besu/docker-compose-active.yml is static (tracked); this script writes the
  machine-specific genesis.json, keys/ and network/besu/.env (all git-ignored).
* The compose file publishes JSON-RPC on 127.0.0.1 only, enables only the
  ETH/NET/WEB3/QBFT APIs, and allows no browser origins (browsers go through the
  authenticated backend relay /api/chain/rpc).
"""

import argparse
import json
import shutil
import subprocess
import sys
import time
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
BESU = ROOT / "network" / "besu"
IMAGE = "hyperledger/besu:26.8.1"

CONFIG = {
    "genesis": {
        "config": {
            "chainId": 13371,
            "homesteadBlock": 0, "eip150Block": 0, "eip155Block": 0, "eip158Block": 0,
            "byzantiumBlock": 0, "constantinopleBlock": 0, "petersburgBlock": 0, "istanbulBlock": 0,
            "berlinBlock": 0, "londonBlock": 0, "shanghaiBlock": 0,
            "zeroBaseFee": True,
            "qbft": {"blockperiodseconds": 2, "epochlength": 30000, "requesttimeoutseconds": 4},
        },
        "gasLimit": "0x1fffffffffffff",
        "difficulty": "0x1",
        "coinbase": "0x0000000000000000000000000000000000000000",
        "alloc": {},
    },
    "blockchain": {"nodes": {"generate": True, "count": 3}},
}


def write_node_env() -> None:
    """network/besu/.env (git-ignored) carries this machine's node1 public enode, which the
    static docker-compose-active.yml uses as the bootnode for nodes 2 and 3."""
    enode = (BESU / "networkFiles" / "keys" / "node1" / "key.pub").read_text(encoding="utf-8").strip().removeprefix("0x")
    (BESU / ".env").write_text(
        "# Generated by scripts/generate_besu_network.py (public key only)\n"
        f"BESU_NODE1_ENODE={enode}\n",
        encoding="utf-8",
    )


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--force", action="store_true")
    a = ap.parse_args()
    data = BESU / "data"
    # Empty node folders (created by an earlier run or by Docker) are not chain data.
    if data.exists() and any(p.is_file() for p in data.rglob("*")):
        if not a.force:
            print("network/besu/data holds chain data from an earlier network. Stop the nodes "
                  "(npm run besu:down), then re-run with --force: the old data is moved aside, not deleted.")
            return 2
        archive = BESU / f"data_archived_{time.strftime('%Y%m%d_%H%M%S')}"
        shutil.move(str(data), str(archive))
        print(f"Existing chain data moved to {archive.relative_to(BESU.parent.parent)}")

    work = BESU / "_generate"
    shutil.rmtree(work, ignore_errors=True)
    work.mkdir()
    (work / "config.json").write_text(json.dumps(CONFIG, indent=2), encoding="utf-8")
    subprocess.run(
        # Generate inside the container, then copy out (Windows bind mounts confuse Besu's
        # "output directory already exists" check).
        ["docker", "run", "--rm", "-v", f"{work.as_posix()}:/work", "--entrypoint", "sh", IMAGE, "-c",
         "besu operator generate-blockchain-config --config-file=/work/config.json --to=/tmp/out "
         "--private-key-file-name=key && cp -r /tmp/out /work/out"],
        check=True, stdout=subprocess.DEVNULL,
    )
    out = work / "out"
    keys = sorted(p for p in (out / "keys").iterdir() if p.is_dir())
    if len(keys) != 3:
        raise SystemExit("expected 3 generated validator keys")

    nf = BESU / "networkFiles"
    shutil.rmtree(nf / "keys", ignore_errors=True)
    (nf / "keys").mkdir(parents=True)
    validators = []
    for i, k in enumerate(keys, start=1):
        dst = nf / "keys" / f"node{i}"
        dst.mkdir()
        shutil.copy2(k / "key", dst / "key")
        shutil.copy2(k / "key.pub", dst / "key.pub")
        validators.append(k.name)
    genesis = json.loads((out / "genesis.json").read_text(encoding="utf-8"))
    genesis["alloc"] = {}
    (nf / "genesis.json").write_text(json.dumps(genesis, indent=2), encoding="utf-8")

    write_node_env()
    shutil.rmtree(work, ignore_errors=True)
    for n in (1, 2, 3):
        (data / f"node{n}").mkdir(parents=True, exist_ok=True)
    print("Generated QBFT network: chain 13371, validators:", ", ".join(validators))
    print("Genesis alloc: none (zero-fee network). Keys: network/besu/networkFiles/keys/ (git-ignored)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
