"""Application configuration loaded from environment variables / backend/.env.

There are NO built-in secret defaults. Every secret (session signing key, data
encryption keys, credential-signing key, chain-operator key) must be supplied through
the environment or the git-ignored backend/.env generated by
`python scripts/init_secrets.py`. Startup fails closed when any is missing or weak.

ENVIRONMENT defaults to "production", so a deployment that forgets to configure itself
gets the strictest validation rather than silently running on development settings.
"""

import base64
from pathlib import Path
from typing import List, Literal
from urllib.parse import urlparse

from pydantic import model_validator
from pydantic_settings import BaseSettings

BASE_DIR = Path(__file__).resolve().parent.parent.parent

# Markers of placeholder / previously published development secrets.
_WEAK_SECRET_MARKERS = ("development", "change-me", "changeme", "replace", "secret-key", "example", "test-secret")


def _is_weak_secret(value: str, min_len: int = 32) -> bool:
    low = (value or "").lower()
    return len(value or "") < min_len or any(m in low for m in _WEAK_SECRET_MARKERS) or len(set(value)) < 8


def _valid_fernet_key(key: str) -> bool:
    try:
        return len(base64.urlsafe_b64decode(key.encode())) == 32
    except Exception:
        return False


class Settings(BaseSettings):
    APP_VERSION: str = "2.0.0"
    ENVIRONMENT: Literal["development", "test", "production"] = "production"
    DEBUG: bool = False

    # Database (credentials come from the environment in every environment)
    DATABASE_URL: str = ""
    DATABASE_URL_SYNC: str = ""

    # CORS & WebAuthn
    CORS_ORIGINS: List[str] = ["http://localhost:5173", "http://127.0.0.1:5173"]
    RP_ID: str = "localhost"
    WEBAUTHN_ORIGINS: List[str] = ["http://localhost:5173", "http://127.0.0.1:5173"]

    # Session tokens (HS256). Used ONLY for session JWTs.
    JWT_SECRET: str = ""
    JWT_ALGORITHM: str = "HS256"
    JWT_EXPIRE_MINUTES: int = 30

    # At-rest encryption of TOTP secrets and wallet wrapping secrets.
    # Comma-separated Fernet keys; the FIRST encrypts, all of them decrypt (rotation).
    DATA_ENCRYPTION_KEYS: str = ""

    # Signing key for issued verifiable credentials (separate purpose from sessions).
    VC_SIGNING_SECRET: str = ""

    # Blockchain
    RPC_URL: str = "http://127.0.0.1:8545"
    CHAIN_ID: int = 13371
    CONTRACT_DEPLOYMENT_PATH: str = str(BASE_DIR.parent / "contracts" / "deployments" / "besu.json")
    # Backend chain-operator key: holds REGISTRAR_ROLE only (grants/revokes the on-chain
    # roles of Manager/Admin/Auditor wallets as identities change). It cannot mint.
    CHAIN_OPERATOR_PRIVATE_KEY: str = ""
    # JSON-RPC methods the authenticated browser relay (/api/chain/rpc) may call.
    CHAIN_RELAY_METHODS: List[str] = [
        "eth_chainId", "net_version", "eth_blockNumber", "eth_call", "eth_estimateGas", "eth_gasPrice",
        "eth_maxPriorityFeePerGas", "eth_feeHistory", "eth_getBlockByNumber", "eth_getTransactionCount",
        "eth_getTransactionReceipt", "eth_getTransactionByHash", "eth_sendRawTransaction", "eth_getCode",
    ]

    # Public base URL of the LexCorp2 web app; QR codes point to its /verify pages.
    PUBLIC_BASE_URL: str = "http://localhost:5173"

    OFFCHAIN_STORAGE_DIR: str = str(BASE_DIR / "offchain_storage")
    IPFS_GATEWAY: str = "http://127.0.0.1:5001"

    NONCE_EXPIRY_SECONDS: int = 300

    # Session hardening
    INACTIVITY_TIMEOUT_MINUTES: int = 15
    TRUSTED_PROXIES: List[str] = ["127.0.0.1/32", "::1/128"]

    STEP_UP_TTL_SECONDS: int = 300
    WEBAUTHN_CHALLENGE_TTL_SECONDS: int = 300

    DOWNLOAD_APPROVAL_TTL_HOURS: int = 24
    DOWNLOAD_REQUIRES_OWNER_APPROVAL: bool = True

    PROVISIONING_PIN_TTL_HOURS: int = 3

    # How AI (Isolation Forest) scores become alert-raising labels:
    #   calibrated (default) - relative to the model's scores for ordinary reference activity
    #   raw                  - the model's native tiers (rates most activity HIGH; see docs)
    #   off                  - AI never raises alerts (rule-based detections still do)
    AI_ALERT_MODE: Literal["calibrated", "raw", "off"] = "calibrated"

    @property
    def data_encryption_keys(self) -> List[str]:
        return [k.strip() for k in self.DATA_ENCRYPTION_KEYS.split(",") if k.strip()]

    @property
    def is_production(self) -> bool:
        return self.ENVIRONMENT == "production"

    @model_validator(mode="after")
    def validate_security_settings(self) -> "Settings":
        problems: List[str] = []

        # --- required in every environment (there are no defaults to fall back on)
        if not self.DATABASE_URL:
            problems.append("DATABASE_URL is not set")
        if _is_weak_secret(self.JWT_SECRET):
            problems.append("JWT_SECRET must be set to a random value of at least 32 characters")
        keys = self.data_encryption_keys
        if not keys:
            problems.append("DATA_ENCRYPTION_KEYS is not set")
        elif not all(_valid_fernet_key(k) for k in keys):
            problems.append("DATA_ENCRYPTION_KEYS must contain valid Fernet keys")
        if _is_weak_secret(self.VC_SIGNING_SECRET):
            problems.append("VC_SIGNING_SECRET must be set to a random value of at least 32 characters")
        if self.JWT_SECRET and self.VC_SIGNING_SECRET and self.JWT_SECRET == self.VC_SIGNING_SECRET:
            problems.append("JWT_SECRET and VC_SIGNING_SECRET must be different keys")
        if self.JWT_SECRET and self.JWT_SECRET in keys:
            problems.append("JWT_SECRET must not be reused as a data encryption key")

        # --- production-only hardening
        if self.is_production:
            if self.DEBUG:
                problems.append("DEBUG must be false in production")
            if not self.CHAIN_OPERATOR_PRIVATE_KEY:
                problems.append("CHAIN_OPERATOR_PRIVATE_KEY is not set")
            db_password = urlparse(self.DATABASE_URL.replace("+asyncpg", "")).password or ""
            if _is_weak_secret(db_password, min_len=16) or db_password == "lexcorp_dev":
                problems.append("the database password in DATABASE_URL is a development/weak value")
            if "*" in self.CORS_ORIGINS:
                problems.append("wildcard '*' is not allowed in CORS_ORIGINS")
            for origin in self.WEBAUTHN_ORIGINS + self.CORS_ORIGINS + [self.PUBLIC_BASE_URL]:
                if not origin.startswith("https://"):
                    problems.append(f"origin {origin} must use HTTPS in production")
        else:
            if "*" in self.CORS_ORIGINS:
                problems.append("wildcard '*' is not allowed in CORS_ORIGINS")
            for origin in self.WEBAUTHN_ORIGINS:
                if origin.startswith("http://") and not (origin.startswith("http://localhost") or origin.startswith("http://127.0.0.1")):
                    problems.append(f"insecure WebAuthn origin {origin}; use HTTPS")

        if problems:
            raise ValueError(f"Refusing to start ({self.ENVIRONMENT}): " + "; ".join(problems))
        return self

    model_config = {
        "env_file": [str(BASE_DIR / ".env")],
        "case_sensitive": True,
        "extra": "ignore",
        # Validation errors must never echo configuration values (they include secrets).
        "hide_input_in_errors": True,
    }


settings = Settings()
