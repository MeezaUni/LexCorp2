#!/bin/sh
# LexCorp2 remote-access VPN server (OpenVPN Community Edition).
#
# First start: creates the certificate authority, the server certificate, one shared client
# certificate for the demo profile, and the tls-crypt-v2 keys, all under /data (git-ignored).
# Every start: writes the server configuration and the client profile
# /data/client/lexcorp2-remote.ovpn, sets the firewall, and starts OpenVPN.
#
# Who may connect is decided at every connection by the sign-in service (entrypoint-auth.sh):
# the person signs in with Google in their browser and must be on ALLOWED_EMAILS. OpenVPN
# waits on its management interface ("management-hold") until that service is attached, so
# nobody can connect without the sign-in step. Connected people can reach only the LexCorp2
# web proxy (APP_IP, HTTPS); everything else is dropped.
set -eu

: "${VPN_HOST:?set VPN_HOST in network/vpn/.env}"
VPN_PORT="${VPN_PORT:-1194}"
VPN_SUBNET="${VPN_SUBNET:-10.8.0.0}"
VPN_NETMASK="${VPN_NETMASK:-255.255.255.0}"
APP_IP="${APP_IP:-172.30.0.10}"
MGMT_ADDR="${MGMT_ADDR:-172.30.0.2}"
MGMT_PORT="${MGMT_PORT:-7505}"

export EASYRSA_PKI=/data/pki EASYRSA_BATCH=1 EASYRSA_NO_VARS=1 EASYRSA_ALGO=ec EASYRSA_CURVE=secp384r1 \
       EASYRSA_DN=cn_only EASYRSA_CA_EXPIRE=3650 EASYRSA_CERT_EXPIRE=825
EASYRSA=/usr/share/easy-rsa/easyrsa
umask 077
mkdir -p /data/secrets /data/shared /data/client

if [ ! -f /data/pki/ca.crt ]; then
  echo "Creating the VPN certificate authority and certificates (first start)"
  "$EASYRSA" init-pki
  EASYRSA_REQ_CN="LexCorp2 VPN CA" "$EASYRSA" build-ca nopass
  "$EASYRSA" build-server-full lexcorp2-vpn-server nopass
  "$EASYRSA" build-client-full lexcorp2-remote nopass
fi
if [ ! -f /data/secrets/tls-crypt-v2-server.key ]; then
  openvpn --genkey tls-crypt-v2-server /data/secrets/tls-crypt-v2-server.key
  openvpn --tls-crypt-v2 /data/secrets/tls-crypt-v2-server.key --genkey tls-crypt-v2-client /data/secrets/tls-crypt-v2-client.key
fi
# /data/shared holds only what the sign-in service needs (its container mounts just this folder)
if [ ! -f /data/shared/management-password.txt ]; then
  openssl rand -hex 32 > /data/shared/management-password.txt
fi
if [ ! -f /data/shared/http-secret.txt ]; then
  openssl rand -hex 16 > /data/shared/http-secret.txt    # 32 characters: the sign-in service's cookie key
fi

cat > /data/server.conf <<EOF
# Generated by entrypoint-openvpn.sh at every start; edit the script, not this file.
port 1194
proto udp
dev tun0
topology subnet
server ${VPN_SUBNET} ${VPN_NETMASK}

# Split tunnel: only the LexCorp2 web proxy is reached through the VPN; everything else
# (the person's own internet traffic) stays on their own connection.
push "route ${APP_IP} 255.255.255.255"

ca /data/pki/ca.crt
cert /data/pki/issued/lexcorp2-vpn-server.crt
key /data/pki/private/lexcorp2-vpn-server.key
dh none
tls-crypt-v2 /data/secrets/tls-crypt-v2-server.key
tls-version-min 1.2
tls-cert-profile preferred
data-ciphers AES-256-GCM:CHACHA20-POLY1305
auth SHA256
allow-compression no

# Sign-in on every connection: OpenVPN asks the sign-in service (management-client-auth),
# which sends the person's browser to Google and checks the email against ALLOWED_EMAILS.
# The profile's certificate is required as well; the Google sign-in is what identifies the person.
management ${MGMT_ADDR} ${MGMT_PORT} /data/shared/management-password.txt
management-hold
management-client-auth
auth-user-pass-optional
# No mid-session renegotiation, so a connected person is not asked to sign in again partway through
# (the client profile says the same).
reneg-sec 0
auth-nocache

keepalive 10 120
persist-key
persist-tun
explicit-exit-notify 1
push "explicit-exit-notify"
# Data-channel offload needs a kernel module that containers don't have
disable-dco
user nobody
group nogroup
verb 3
errors-to-stderr
EOF

cat > /data/client/lexcorp2-remote.ovpn <<EOF
# LexCorp2 remote access (demo). Import into the OpenVPN Community client (OpenVPN GUI 2.6+).
# Connecting opens your browser to sign in with Google; only approved accounts are let in.
client
dev tun
proto udp
remote ${VPN_HOST} ${VPN_PORT}
resolv-retry infinite
nobind
persist-tun
remote-cert-tls server
verify-x509-name lexcorp2-vpn-server name
tls-version-min 1.2
data-ciphers AES-256-GCM:CHACHA20-POLY1305
auth SHA256
auth-nocache
reneg-sec 0
push-peer-info
verb 3

<ca>
$(cat /data/pki/ca.crt)
</ca>
<cert>
$(openssl x509 -in /data/pki/issued/lexcorp2-remote.crt)
</cert>
<key>
$(cat /data/pki/private/lexcorp2-remote.key)
</key>
<tls-crypt-v2>
$(cat /data/secrets/tls-crypt-v2-client.key)
</tls-crypt-v2>
EOF
echo "Client profile written to network/vpn/data/client/lexcorp2-remote.ovpn (remote ${VPN_HOST}:${VPN_PORT})"

# Firewall: VPN clients may open HTTPS to the web proxy and nothing else, and never this container.
iptables -F FORWARD
iptables -P FORWARD DROP
iptables -A FORWARD -m conntrack --ctstate ESTABLISHED,RELATED -j ACCEPT
iptables -A FORWARD -i tun0 -d "${APP_IP}" -p tcp --dport 443 -j ACCEPT
iptables -A FORWARD -i tun0 -d "${APP_IP}" -p icmp --icmp-type echo-request -j ACCEPT
iptables -F INPUT
iptables -A INPUT -i lo -j ACCEPT
iptables -A INPUT -m conntrack --ctstate ESTABLISHED,RELATED -j ACCEPT
iptables -A INPUT -i tun0 -j DROP

mkdir -p /dev/net
[ -c /dev/net/tun ] || mknod /dev/net/tun c 10 200
exec openvpn --config /data/server.conf
